"""Pack the existing background RLE and boot-only font into its 16 KiB ROM."""
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    header = (ROOT / "sw/driver/asset_rom.h").read_text(encoding="utf-8")
    offset = int(re.search(r"#define FONT_ROM_OFFSET (0x[0-9A-Fa-f]+)u", header)[1], 16)
    source = (ROOT / "sw/app/visual_assets.c").read_text(encoding="utf-8")
    initializer = re.search(r"const uint8_t visual_font\[95\]\[8\] = (\{.*?\});", source, re.S)
    if not initializer:
        raise ValueError("visual_font initializer not found")
    rows = ast.literal_eval(initializer[1].replace("{", "[").replace("}", "]"))
    if len(rows) != 95 or any(len(row) != 8 for row in rows):
        raise ValueError("font must be 95 glyphs of eight bytes")
    font = bytes(value for row in rows for value in row)
    bg = bytes(int(word, 16) for word in (ROOT / "rtl/bitblt/bg_rle.hex").read_text().split())
    if len(bg) > offset or offset + len(font) > 16384:
        raise ValueError("background/font exceeds shared asset ROM")
    packed = bg.ljust(offset, b"\0") + font
    packed = packed.ljust(16384, b"\0")
    out = ROOT / "rtl/bitblt/asset_rom.hex"
    out.write_text("".join(f"{byte:02x}\n" for byte in packed), encoding="ascii")
    (out.parent / "asset_rom_path.vh").write_text(
        f'// Generated by tools/build_asset_rom.py.\n`define ASSET_ROM_INIT_FILE "{out.as_posix()}"\n',
        encoding="ascii")
    assert packed[:len(bg)] == bg and packed[offset:offset + 760] == font
    print(f"Asset ROM: {len(bg)} background bytes + {len(font)} font bytes in 16384 bytes")


if __name__ == "__main__":
    main()
