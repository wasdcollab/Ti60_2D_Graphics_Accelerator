"""Losslessly pack backgrounds, all sprite streams and skill LUTs into 16 KiB."""
import ast,json,math,re,struct
from pathlib import Path
from asset_lz import pack,unpack
ROOT=Path(__file__).resolve().parents[1]


def main():
    from build_spell_params import main as build_params
    build_params()
    offset=0x3c00
    source=(ROOT/'sw/build/visual_assets_rom_source.c').read_text(encoding='utf-8')
    m=re.search(r'const uint8_t visual_font\[95\]\[8\] = (\{.*?\});',source,re.S)
    rows=ast.literal_eval(m[1].replace('{','[').replace('}',']'))
    font=bytes(v for row in rows for v in row);assert len(font)==760
    bg=bytes(int(x,16) for x in (ROOT/'rtl/bitblt/bg_rle.hex').read_text().split())
    payload=bytearray(bg)
    defines=['/* Generated: lossless boot-unpacked DDR pointers. */','#include "memory_map.h"']
    manifest={}
    def put(name,data,ctype,shape=''):
        payload.extend(b'\0'*((-len(payload))&3));at=len(payload);payload.extend(data)
        ptr=f'((const {ctype} (*){shape})(MM_ASSET_UNPACK + {at}u))' if shape else f'((const {ctype} *)(MM_ASSET_UNPACK + {at}u))'
        defines.append(f'#define {name} {ptr}');manifest[name]=dict(offset=at,bytes=len(data))
    arc=[round(v*89.6) for i in range(54) for v in (math.cos(math.pi*.75+math.pi*.75*i/53),-math.sin(math.pi*.75+math.pi*.75*i/53))]
    laser=[round(v*256) for i in range(18) for v in (math.cos(math.pi/2+math.pi/2*i/17),-math.sin(math.pi/2+math.pi/2*i/17))]
    put('skill1_arc',struct.pack('108b',*arc),'int8_t','[2]')
    put('skill1_laser',struct.pack('<36h',*laser),'int16_t','[2]')
    put('skill1_side',struct.pack('<54h',*[round(math.sin(i/53*4*math.pi)*120) for i in range(54)]),'int16_t')
    put('spell_sine',struct.pack('<256h',*[round(math.sin(i*2*math.pi/256)*16384) for i in range(256)]),'int16_t')
    for match in list(re.finditer(r'static const (uint8_t|uint32_t) ([pr]_\w+)\[\] = (\{.*?\});',source,re.S)):
        vals=[int(v.strip().rstrip('uU'),0) for v in match[3][1:-1].split(',') if v.strip()]
        data=bytes(vals) if match[1]=='uint8_t' else struct.pack('<%dI'%len(vals),*vals)
        put(match[2],data,match[1]);source=source.replace(match[0],'')
    packed=pack(payload);assert len(packed)<=offset and len(payload)<=0x8000
    assert unpack(packed,len(payload))[:len(bg)]==bg
    defines += [f'#define ASSET_PACKED_BYTES {len(packed)}u',f'#define ASSET_UNPACK_BYTES {len(payload)}u']
    (ROOT/'sw/app/asset_rom_extra.h').write_text('\n'.join(defines)+'\n',encoding='ascii')
    (ROOT/'sw/app/visual_assets.c').write_text('#include "asset_rom_extra.h"\n'+source,encoding='utf-8')
    rom=packed.ljust(offset,b'\0')+font;rom=rom.ljust(16384,b'\0')
    out=ROOT/'rtl/bitblt/asset_rom.hex';out.write_text(''.join(f'{v:02x}\n' for v in rom),encoding='ascii')
    (out.parent/'asset_rom_path.vh').write_text(f'// Generated by tools/build_asset_rom.py.\n`define ASSET_ROM_INIT_FILE "{out.as_posix()}"\n',encoding='ascii')
    (ROOT/'sw/build/asset_unpack.bin').write_bytes(payload)
    (ROOT/'sw/build/asset_manifest.json').write_text(json.dumps(dict(packed_bytes=len(packed),unpacked_bytes=len(payload),arrays=manifest),indent=2))
    print(f'Asset ROM: {len(payload)} bytes losslessly packed to {len(packed)} + {len(font)} font bytes in 16384')


if __name__=='__main__':main()
