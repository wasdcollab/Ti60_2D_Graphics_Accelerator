"""Build the embedded, low-rate ROM from licensed game sound effects.

Input files are deliberately not committed: Taira Komori permits embedding in
a work but prohibits redistributing the raw assets.  This produces only the
derived FPGA ROM and the matching address constants.
"""
from pathlib import Path
import pygame

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "audio" / "source"
OUT = ROOT / "rtl" / "audio"
RATE = 1600
CAPACITY = 8192
ASSETS = (
    ("SHOT", "shoot2.mp3", 800),
    ("KILL", "game_explosion3.mp3", 2400),
    ("BOSS", "large_destruction1.mp3", 4700),
)

pygame.mixer.pre_init(44100, -16, 1)
pygame.init()
data = []
defs = []
for name, filename, limit in ASSETS:
    raw = pygame.mixer.Sound(str(SRC / filename)).get_raw()
    samples = [int.from_bytes(raw[i:i + 2], "little", signed=True)
               for i in range(0, len(raw) - 1, 2)]
    count = min(limit, (len(samples) * RATE) // 44100)
    clip = [samples[(i * 44100) // RATE] for i in range(count)]
    peak = max((abs(x) for x in clip), default=1)
    clip = [max(-128, min(127, (x * 110) // peak)) for x in clip]
    defs.append((name, len(data), len(clip)))
    data.extend((x & 0xFF) for x in clip)

if len(data) > CAPACITY:
    raise SystemExit(f"SFX ROM overflow: {len(data)} > {CAPACITY}")
data.extend([0] * (CAPACITY - len(data)))
(OUT / "sfx_rom.hex").write_text("".join(f"{x:02x}\n" for x in data), encoding="ascii")
lines = ["// Generated by tools/build_audio_sfx_rom.py; do not edit."]
for name, start, length in defs:
    lines.append(f"localparam [12:0] SFX_{name}_START = 13'd{start};")
    lines.append(f"localparam [12:0] SFX_{name}_LEN = 13'd{length};")
(OUT / "sfx_rom.vh").write_text("\n".join(lines) + "\n", encoding="ascii")
print("SFX ROM:", len(data), "bytes; payload", sum(x[2] for x in defs), "bytes")
