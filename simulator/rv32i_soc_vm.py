    def save_frame_bmp(self, filepath, base_addr=None):
        if base_addr is None:
            base_addr = self.right_request
        self.drain()                    # CPU stores still in flight belong in it
        w, h = SCREEN_W, SCREEN_H
        # Repack row by row.  A frame row pitches by SCREEN_PITCH (2048 pixels)
        # and only its first SCREEN_W (1366) are visible; handing the raw buffer
        # to a 1366-wide BMP header slid 682 hidden pixels into the start of
        # every row, so every exported picture came out as a repeating
        # parallelogram instead of the frame the scanout would have shown.
        rows = bytearray(w * h * 4)
        view = memoryview(rows)
        fb = self.fb[base_addr]
        for y in range(h):
            at = y * SCREEN_PITCH
            view[y * w * 4:(y + 1) * w * 4] = fb[at:at + w].tobytes()
        pixels_bytes = bytes(rows)
        filesize = 54 + len(pixels_bytes)
        header = struct.pack('<2sIHHIIiiHHIIiiII', b'BM', filesize, 0, 0, 54, 40,
                             w, -h, 1, 32, 0, len(pixels_bytes), 0, 0, 0, 0)
        Path(filepath).parent.mkdir(parents=True, exist_ok=True)
        with open(filepath, 'wb') as f:
            f.write(header)
            f.write(pixels_bytes)
