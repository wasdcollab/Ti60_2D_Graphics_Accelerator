#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
simulator/rv32i_soc_vm.py
=========================
Standalone virtual machine for the Ti60 2D graphics accelerator:

    RV32I sapphire core + APB3 peripherals + BitBlt engine + DDR3 memory

It runs the *real* firmware binary produced by the GCC flow
(sw/build/firmware.bin) with no board attached, and it models the BitBlt
engine with the same byte semantics as rtl/bitblt (v2):

  * OP_FILL : every byte of [dst_off, dst_off + 4*w) on every row, byte
              granular (matches the rotated colour register in the RTL)
  * OP_COPY : byte exact block copy with independent row strides; the source
              and destination low nibbles may differ, which is exactly the
              case the v1 engine got wrong

Memory map
    0xF900_0000  64 KiB on-chip RAM (firmware image + stack)
    0xF810_0000  APB3 peripheral window (BitBlt registers, gamepad, switches)
    0x0080_0000  framebuffer A (1366x768 ARGB8888, double buffered)
    0x0130_0000  framebuffer B
    0x0160_0000  64 KiB DDR scratch (650 entity records + sprite tile)
"""
import struct
from array import array
from pathlib import Path

RAM_BASE = 0xF9000000
RAM_SIZE = 64 * 1024
RAM_STACK_FLOOR = 0xF900FC00        # keep in sync with sw/linker/ti60_sapphire.ld

APB_BASE = 0xF8100000

# Visible scan geometry.  Kept here because the BitBlt model below derives x/y
# from a byte offset and must agree with the framebuffer pitch the firmware uses.
SCREEN_W = 1366
SCREEN_H = 768
SCREEN_STRIDE = 8192       # framebuffer row pitch (bytes)
SCREEN_PITCH = SCREEN_STRIDE // 4   # ... in pixels
HALF_PIXELS = 640           # left/right scanout split, see the VDMA HALF_OFFSET
FRAME_BASES = (0x00800000, 0x00E00000)
FRAME_BYTES = SCREEN_H * SCREEN_STRIDE
# The two framebuffers must not overlap: frame_of() returns the FIRST base whose
# range contains an address, so an overlap would silently route FB B traffic to FB A.
assert FRAME_BASES[1] >= FRAME_BASES[0] + FRAME_BYTES, \
    "framebuffer B overlaps framebuffer A"

SCRATCH_BASE = 0x01600000
# Sapphire's first UART.  See
# embedded_sw/soc/bsp/efinix/EfxSapphireSoc/include/soc.h
# (SYSTEM_UART_0_IO_CTRL 0xf8010000) and driver/uart.h for the layout.
# It is modelled only so the firmware's diagnostic log has somewhere to go.
UART_BASE = 0xF8010000
SCRATCH_SIZE = 0x2A00000            # pools, artwork, fonts, the three
                                    # 1366x768 stage plates and the painted
                                    # plate at 0x03800000.  Upper bound
                                    # 0x04000000, i.e. 40 MB of the board's
                                    # 256 MB; AXI addresses are 28 bits.
                                    # composed layers, MM_CARD_BG, MM_LANCE

TICK_STEPS = 25000                  # ~60 Hz at the modelled instruction rate

def _load_asset_rom():
    """The backdrop RLE bank, as shipped in the bitstream's asset ROM.

    rtl/bitblt/bg_rle.hex is generated by tools/build_stage_backgrounds.py and
    loaded into rtl/bitblt/bitblt_asset_rom.v, whose BRAM the BitBlt APB window
    exposes at 0x80 (index) / 0x84 (byte).  The firmware copies the whole ROM
    into DDR once at boot, so the model has to serve those reads - without them
    every stage plate decodes from zeroes and each backdrop comes out blank.
    """
    path = Path(__file__).resolve().parents[1] / "rtl" / "bitblt" / "bg_rle.hex"
    if not path.exists():
        return b""
    return bytes(int(tok, 16) for tok in path.read_text(encoding="ascii").split())


# One display tick stands for one 75 Hz frame period of GAME time: the core
# tick counter below is mapped so that TICK_STEPS instructions equal exactly
# 100e6/75 = 1333333 core ticks, the firmware's LOGIC_STEP_CYCLES.  The
# scanout's nominal 60 Hz is irrelevant to the fixed-step simulation, which
# only reads the counter.


# Sign-extension masks, precomputed.  sign_extend() is called about once per
# executed instruction, and rebuilding both masks from `bits` on every call
# was a measurable share of the model's inner loop.
_SE_MASK = [0] * 33
_SE_SIGN = [0] * 33
for _b in range(1, 33):
    _SE_MASK[_b] = (1 << _b) - 1
    _SE_SIGN[_b] = 1 << (_b - 1)


def sign_extend(val, bits):
    return (val & _SE_MASK[bits]) - ((val & _SE_SIGN[bits]) << 1)


def load_firmware(path):
    """Return (words, nbytes, bss_range) for a .bin or .elf firmware image.

    bss_range is the address range of the SHT_NOBITS section (the zero
    initialised statics).  It lives at the very end of the linked image, so the
    "did the CPU write into its own code" guard has to know about it - .bss is
    RAM, not code, even though it sits inside the loaded image extent.
    """
    path = Path(path)
    raw = path.read_bytes()
    if raw[:4] == b"\x7fELF":
        words, nbytes = elf_to_words(raw)
        bss = elf_bss_range(raw)
    else:
        words = [int.from_bytes(raw[i:i+4].ljust(4, b"\x00"), "little")
                 for i in range(0, len(raw), 4)]
        nbytes = len(raw)
        bss = sidecar_sym(path)
    return words, nbytes, bss


def sidecar_sym(path):
    """Writable-RAM layout published next to the binary by the build.

    Returns (writable_start, bss_end) or None.  Everything from writable_start
    on is RAM (.data then .bss); anything below it is code or read-only data.
    """
    sym = Path(path).with_suffix(".sym")
    if not sym.exists():
        return None
    vals = {}
    for line in sym.read_text(encoding="ascii", errors="replace").splitlines():
        parts = line.split()
        if len(parts) == 2:
            try:
                vals[parts[0]] = int(parts[1], 16)
            except ValueError:
                pass
    start = vals.get("data_start", vals.get("bss_start"))
    end = vals.get("bss_end", vals.get("image_end"))
    if start is None or end is None:
        return None
    return (start, end)


def elf_bss_range(raw):
    """Address range of the .bss (SHT_NOBITS) sections, or None."""
    try:
        (e_shoff,) = struct.unpack_from("<I", raw, 0x20)
        (e_shentsize,) = struct.unpack_from("<H", raw, 0x2E)
        (e_shnum,) = struct.unpack_from("<H", raw, 0x30)
    except struct.error:
        return None
    if not e_shoff or not e_shnum:
        return None
    lo = hi = None
    for i in range(e_shnum):
        off = e_shoff + i * e_shentsize
        sh_type = struct.unpack_from("<I", raw, off + 4)[0]
        if sh_type != 8:                       # SHT_NOBITS
            continue
        sh_addr, _sh_offset, sh_size = struct.unpack_from("<III", raw, off + 12)
        if sh_size == 0:
            continue
        lo = sh_addr if lo is None else min(lo, sh_addr)
        hi = sh_addr + sh_size if hi is None else max(hi, sh_addr + sh_size)
    return None if lo is None else (lo, hi)


def elf_to_words(raw):
    """Minimal ELF32 little-endian program-header reader (no pyelftools)."""
    (e_phoff,) = struct.unpack_from("<I", raw, 0x1C)
    (e_phentsize,) = struct.unpack_from("<H", raw, 0x2A)
    (e_phnum,) = struct.unpack_from("<H", raw, 0x2C)
    image = bytearray()
    base = None
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        p_type, p_offset, p_vaddr, _, p_filesz = struct.unpack_from("<IIIII", raw, off)
        if p_type != 1 or p_filesz == 0:          # PT_LOAD only
            continue
        if base is None:
            base = p_vaddr
        start = p_vaddr - base
        if len(image) < start:
            image += b"\x00" * (start - len(image))
        image[start:start + p_filesz] = raw[p_offset:p_offset + p_filesz]
    if base != RAM_BASE:
        raise SystemExit("ELF load address %#x is not the SoC RAM base %#x"
                         % (base or 0, RAM_BASE))
    words = [int.from_bytes(image[i:i+4].ljust(4, b"\x00"), "little")
             for i in range(0, len(image), 4)]
    return words, len(image)


class SapphireSoCVM:
    def __init__(self, code_words, latency=10, stack_floor=RAM_STACK_FLOOR,
                 bss=None):
        self.ram = bytearray(RAM_SIZE)
        for i, w in enumerate(code_words):
            self.ram[i*4:i*4+4] = (w & 0xFFFFFFFF).to_bytes(4, "little")
        # Word view of the very same buffer: the model reads and writes about
        # one instruction or word per step, and a view beats slice+
        # from_bytes by a wide margin.  It aliases, so writes through either
        # name are visible through the other.
        self.ram32 = memoryview(self.ram).cast("I")
        self.image_end = RAM_BASE + len(code_words) * 4
        self.bss = bss                       # (start, end) of the .bss, or None
        self.scratch = bytearray(SCRATCH_SIZE)
        # Backdrop RLE, read back out of the bitstream's asset ROM by the same
        # two APB registers the board uses.  See _load_asset_rom().
        self.asset_rom = _load_asset_rom()
        self.asset_addr = 0

        self.r = [0] * 32
        self.pc = RAM_BASE
        self.steps = 0
        self.tick_left = TICK_STEPS

        # 1366x768 32-bit ARGB framebuffers (double buffering)
        self.fb = {b: array('I', [0xDEADBEEF]) * (FRAME_BYTES // 4) for b in FRAME_BASES}
        self.pending = {}
        self.params = {}

        self.active = self.request = FRAME_BASES[0]
        self.right_active = self.right_request = FRAME_BASES[0]
        self.published = []
        self.right_published = []
        self.cpu_frames = self.fpga_frames = 0

        # peripherals / status
        self.starts = 0
        self.busy_until = 0
        self.done = False
        self.vsync = False
        self.latency = latency
        self.min_sp = RAM_BASE + RAM_SIZE
        self.stack_floor = stack_floor

        # modelled inputs
        self.joy = 0x00008080
        self.btn = 0x00008000
        self.board_keys = 0x00000000

        # statistics
        self.blit_copy_bytes = 0
        self.blit_copy_calls = 0
        self.last_copy = None
        self.blit_fill_calls = 0

        # UART: bytes the firmware printed, and the config writes it made
        self.uart_out = []
        self.uart_cfg = {}

        # OP_ALPHA bookkeeping: last_alpha_before is the background snapshot the
        # engine blended into, which is what an independent checker needs to
        # recompute the expected result.
        self.blit_alpha_calls = 0
        self.blit_alpha_bytes = 0
        self.blit_alpha_keyed = 0
        self.last_alpha = None
        self.last_alpha_cfg = None
        self.last_alpha_before = None
        self.last_alpha_rect = None
        self.blit_add_calls = 0
        self.blit_add_bytes = 0

    def __getstate__(self):
        # ram32 is a view of ram, not data of its own, and views are not
        # picklable: drop it here and let __setstate__ rebuild it.
        state = self.__dict__.copy()
        state.pop("ram32", None)
        return state

    def __setstate__(self, state):
        self.__dict__.update(state)
        self.ram32 = memoryview(self.ram).cast("I")
        # tick_left replaced a per-instruction `steps % TICK_STEPS`, and it
        # is not in the older snapshots.  Rebuild it so the vsync PHASE is
        # exactly what the modulo would have produced from here: the next
        # tick still lands on the next multiple of TICK_STEPS.
        self.tick_left = TICK_STEPS - (self.steps % TICK_STEPS)
        # Snapshots predating the UART model have neither attribute.
        if "uart_out" not in self.__dict__:
            self.uart_out = []
        if "uart_cfg" not in self.__dict__:
            self.uart_cfg = {}
        # Snapshots predating the asset ROM window have neither attribute.
        if "asset_rom" not in self.__dict__:
            self.asset_rom = _load_asset_rom()
        if "asset_addr" not in self.__dict__:
            self.asset_addr = 0

    # ------------------------------------------------------------------
    # memory helpers
    # ------------------------------------------------------------------
    def frame_of(self, addr):
        for base in FRAME_BASES:
            if base <= addr < base + FRAME_BYTES:
                return base
        return None

    def in_scratch(self, addr, size=1):
        return SCRATCH_BASE <= addr <= SCRATCH_BASE + SCRATCH_SIZE - size

    def check_owner(self, base, x=None, hw=False):
        """Ownership guard for the split-screen double buffering scheme.

        The left half of a framebuffer is produced by the CPU and scanned by
        the left video DMA; the right half is produced by the BitBlt engine and
        scanned by the right video DMA.  A producer may therefore touch a
        buffer the *other* scanout is currently reading, as long as it stays on
        its own half - what must never happen is overwriting the half that the
        matching scanout is displaying right now.
        """
        half = (x >= HALF_PIXELS) if x is not None else None
        if hw:
            assert base != self.right_active, \
                "BitBlt wrote the SCAN active right buffer %#x at PC=%#x" % (base, self.pc)
        else:
            assert not (base == self.active and (half is None or not half)), \
                "Prohibited write to SCAN active left buffer %#x at PC=%#x" % (base, self.pc)

    def drain(self):
        for a, v in self.pending.items():
            base = self.frame_of(a)
            self.fb[base][(a - base) // 4] = v
        self.pending.clear()

    def load(self, addr, size=4, signed=False):
        """Byte/half/word load supporting all modelled regions."""
        if size == 4 and not signed and addr & 3 == 0 and \
                RAM_BASE <= addr <= RAM_BASE + RAM_SIZE - 4:
            return self.ram32[(addr - RAM_BASE) >> 2]
        if RAM_BASE <= addr <= RAM_BASE + RAM_SIZE - size:
            return int.from_bytes(self.ram[addr-RAM_BASE:addr-RAM_BASE+size],
                                  "little", signed=signed)
        if self.in_scratch(addr, size):
            return int.from_bytes(self.scratch[addr-SCRATCH_BASE:addr-SCRATCH_BASE+size],
                                  "little", signed=signed)
        assert size == 4, "only word accesses are modelled outside RAM/scratch"
        if addr == 0xF8B0BFF8:
            # Synthetic 100 MHz CLINT aligned to the model's display clock.
            # For control flow only: NOT a board performance prediction.
            return (self.steps * 100_000_000 // (TICK_STEPS * 75)) & 0xFFFFFFFF
        if addr == APB_BASE:
            busy = self.steps < self.busy_until
            return int(busy) | (int(self.done and not busy) << 1)
        if addr == APB_BASE + 0x24:
            v, self.vsync = int(self.vsync), False
            return v
        if addr == APB_BASE + 0x28:
            return self.active
        if addr == APB_BASE + 0x2C:
            return self.right_active
        if addr == APB_BASE + 0x34:
            # Packed BCD FPS register. Instruction-time VM is not a board FPS
            # measurement; zero unless a test explicitly supplies a value.
            return self.params.get(0x34, 0)
        if addr == APB_BASE + 0x38:
            return self.cpu_frames
        if addr == APB_BASE + 0x3C:
            return self.fpga_frames
        if addr == APB_BASE + 0x40:
            return self.right_request
        if addr == APB_BASE + 0x50:
            return self.joy
        if addr == APB_BASE + 0x54:
            return self.btn
        if addr == APB_BASE + 0x58:
            return self.board_keys
        if addr == APB_BASE + 0x5C:
            return self.params.get(0x5C, 0x0001005A)
        if addr == APB_BASE + 0x70:
            # Synthetic 100 MHz core-tick counter aligned with the 75 Hz
            # display model: one display frame (TICK_STEPS instructions) is
            # exactly 100e6/75 ticks, matching the board's CORE_TICKS.  The
            # firmware's fixed-step game clock (LOGIC_STEP_CYCLES) reads this
            # register to decide how many logic ticks a display frame owes.
            return (self.steps * 100_000_000 // (TICK_STEPS * 75)) & 0xFFFFFFFF
        if addr == APB_BASE + 0x44:
            # scan_diagnostics: low half is the video DMA underflow counter (how
            # many pixel-clock beats the line FIFO ran dry), high half is the
            # background-error counter.  The model's scanout never starves, so
            # both are 0 - but the firmware reads this every window now, and an
            # unmapped load would abort a whole scenario.
            return 0
        if addr == APB_BASE + 0x74:
            # Live engine probe {sg_state, ar_pend, q_cnt}.  Not applicable here.
            return 0
        if APB_BASE <= addr < APB_BASE + 0x100:
            return self.params.get(addr - APB_BASE, 0)


        if addr == APB_BASE + 0x78:
            # Overlay control word.  The firmware reads it back while paused, so
            # the model has to answer: an unmapped load aborts the scenario.
            return self.params.get(0x78, 0)
        if addr == APB_BASE + 0x7C:
            return self.params.get(0x7C, 0)
        if addr == APB_BASE + 0x88:
            return self.params.get(0x88, 0)
        if addr == APB_BASE + 0x84:
            # Asset ROM byte window.  The plate RLE lives in the bitstream, not
            # in the firmware image, and gpu2d_asset_copy() walks it through
            # this register pair at boot, so the model has to answer.
            i = self.asset_addr
            return self.asset_rom[i] if 0 <= i < len(self.asset_rom) else 0

        if UART_BASE <= addr < UART_BASE + 0x40:
            # STATUS[23:16] is the free space in the TX FIFO (uart.h).  Report
            # it as never full so uart_putc()'s wait loop always falls through;
            # the real FIFO is 128 deep and the log line is ~40 bytes.
            return (0xFF << 16) if (addr - UART_BASE) == 0x04 else 0

        base = self.frame_of(addr)
        assert base is not None, "unmapped load %#x at PC=%#x" % (addr, self.pc)
        assert addr % 4 == 0, "unaligned pixel load %#x" % addr
        self.drain()
        return self.fb[base][(addr - base) // 4]

    def store(self, addr, val, size=4):
        val &= (1 << (size * 8)) - 1
        if RAM_BASE <= addr <= RAM_BASE + RAM_SIZE - size:
            # .data and .bss sit at the tail of the loaded image but they are
            # RAM, so writing them is legitimate; anything below the writable
            # floor would be the CPU trampling its own code or constants.
            floor = self.bss[0] if self.bss is not None else self.image_end
            assert addr >= floor, \
                "CODE OVERWRITE: store=%#x, writable from %#x, PC=%#x" % (
                    addr, floor, self.pc)
            if size == 4 and addr & 3 == 0:
                self.ram32[(addr - RAM_BASE) >> 2] = val
            else:
                self.ram[addr-RAM_BASE:addr-RAM_BASE+size] = val.to_bytes(size, "little")
            return
        if self.in_scratch(addr, size):
            self.scratch[addr-SCRATCH_BASE:addr-SCRATCH_BASE+size] = \
                val.to_bytes(size, "little")
            return

        assert size == 4, "only word stores are modelled outside RAM/scratch"
        if APB_BASE <= addr < APB_BASE + 0x100:
            self._apb_store(addr - APB_BASE, val)
            return

        if UART_BASE <= addr < UART_BASE + 0x40:
            off = addr - UART_BASE
            if off == 0x00:
                self.uart_out.append(val & 0xFF)   # UART_DATA
            else:
                self.uart_cfg[off] = val           # divider / frame config
            return

        base = self.frame_of(addr)
        if base is None:
            import traceback
            print("UNMAPPED STORE %#x pc=%#x" % (addr, self.pc))
            print("  FRAME_BASES=%s FRAME_BYTES=%#x" % (FRAME_BASES, FRAME_BYTES))
            print("  scratch window %#x..%#x" % (
                SCRATCH_BASE, SCRATCH_BASE + SCRATCH_SIZE))
            print("  regs:", {k: hex(v) for k, v in sorted(self.regs.items())}
                  if hasattr(self, "regs") else "n/a")
            traceback.print_stack()
        assert base is not None, "unmapped store %#x at PC=%#x" % (addr, self.pc)
        assert addr % 4 == 0, "unaligned pixel store %#x" % addr
        self.check_owner(base, x=((addr - base) // 4) % SCREEN_PITCH, hw=False)
        self.pending[addr] = val

    # ------------------------------------------------------------------
    # BitBlt engine model (mirrors rtl/bitblt v2 byte semantics)
    # ------------------------------------------------------------------
    def _trace_blit(self, kind, dst, src, w, h, extra=0):
        if not hasattr(self, "_blit_trace"):
            self._blit_trace = []
        self._blit_trace.append((self.steps, kind, dst, src, w, h, extra))
        if len(self._blit_trace) > 400:
            del self._blit_trace[:-400]

    def dump_blit_trace(self, n=40):
        for rec in getattr(self, "_blit_trace", [])[-n:]:
            print("  trace steps=%d %s dst=%#x src=%#x %dx%d arg6=%#x" % rec)
    def _region_read(self, addr, n):
        """Read n bytes from whichever region `addr` belongs to."""
        base = self.frame_of(addr)
        if base is not None:
            assert addr % 4 == 0 and n % 4 == 0, "pixel ops must be word aligned"
            self.drain()
            return self.fb[base][(addr-base)//4:(addr-base+n)//4].tobytes()
        if self.in_scratch(addr, n):
            return bytes(self.scratch[addr-SCRATCH_BASE:addr-SCRATCH_BASE+n])
        raise AssertionError("BitBlt source %#x outside modelled DDR" % addr)

    def _region_write(self, addr, data):
        base = self.frame_of(addr)
        if base is not None:
            assert addr % 4 == 0 and len(data) % 4 == 0
            self.check_owner(base, x=((addr - base) // 4) % SCREEN_PITCH, hw=True)
            arr = array('I')
            arr.frombytes(data)
            n = len(data) // 4
            self.fb[base][(addr-base)//4:(addr-base)//4 + n] = arr
            return
        if self.in_scratch(addr, len(data)):
            self.scratch[addr-SCRATCH_BASE:addr-SCRATCH_BASE+len(data)] = data
            return
        raise AssertionError("BitBlt destination %#x outside modelled DDR" % addr)

    def blit_fill(self, dst, w, h, color, dst_stride):
        self._trace_blit('fill', dst, 0, w, h, 0)
        self.drain()
        assert dst_stride % 16 == 0, "BitBlt strides must be multiples of 16"
        row = array('I', [color]) * w
        base = self.frame_of(dst)
        if base is not None:
            off = dst - base
            assert off % 4 == 0, "fill destination must be word aligned"
            x = (off // 4) % SCREEN_PITCH
            y = (off // 4) // SCREEN_PITCH
            assert 0 <= x and x + w <= SCREEN_W and y + h <= SCREEN_H, \
                "BitBlt fill out of bounds: (%d,%d,%d,%d)" % (x, y, w, h)
            self.check_owner(base, x=x, hw=True)
            for r in range(y, y + h):
                at = r * SCREEN_PITCH + x
                self.fb[base][at:at + w] = row
        else:
            # the engine can also fill plain DDR (used to build the sprite tile)
            last = dst + (h - 1) * dst_stride + 4 * w
            assert self.in_scratch(dst) and last <= SCRATCH_BASE + SCRATCH_SIZE, \
                "BitBlt fill destination %#x outside modelled DDR" % dst
            raw = row.tobytes()
            for r in range(h):
                a = dst + r * dst_stride - SCRATCH_BASE
                self.scratch[a:a + 4 * w] = raw
        self.starts += 1
        self.blit_fill_calls += 1
        self.done = True
        self.busy_until = self.steps + self.latency

    def blit_copy(self, dst, src, w, h, src_stride, dst_stride, colorkey=None):
        self._trace_blit('copy', dst, src, w, h, src_stride)
        # A rolling log of (w, h, src, dst) for every COPY.  Scenarios that
        # grade a COMMAND rather than a picture - "did the card put its columns
        # up" - need to see the command even when the frame they sample was
        # drawn from the other scanout buffer.
        if not hasattr(self, "copy_log"):
            self.copy_log = []
        self.copy_log.append((w, h, src, dst))
        if len(self.copy_log) > 4096:
            del self.copy_log[:2048]
        # Keep the last FULL-SPRITE copy separately.  _blit_trace holds 400
        # records and the HUD's 6x8 glyph copies evict the 64x64 sprite copy
        # within a frame or two, so a scenario that runs for 400k steps and
        # then inspects "the sprite copy" would find nothing.
        if w >= 32 and h >= 32:
            self.last_sprite_copy = (dst, src, w, h, src_stride, dst_stride)
        base0 = self.frame_of(dst)
        if base0 is not None and h == 48 and (dst - base0) // 4 // SCREEN_PITCH > 700:
            print("TALL48 dst=%#x src=%#x w=%d h=%d ss=%#x ds=%#x pc=%#x"
                  % (dst, src, w, h, src_stride, dst_stride, self.pc))
        if w == 64 and h == 64:
            self.last_boss_copy = (dst, src, w, h, src_stride, dst_stride)
        self.drain()
        # the hardware rejects strides that are not a multiple of 16 bytes
        assert src_stride % 16 == 0 and dst_stride % 16 == 0, \
            "BitBlt copy strides must be multiples of 16"
        base = self.frame_of(dst)
        if base is not None:
            off = dst - base
            x = (off // 4) % SCREEN_PITCH
            y = (off // 4) // SCREEN_PITCH
            assert 0 <= x and x + w <= SCREEN_W and y + h <= SCREEN_H, \
                "BitBlt copy out of bounds: (%d,%d,%d,%d)" % (x, y, w, h)
            self.check_owner(base, x=x, hw=True)
        else:
            # Real COPY supports plain DDR, e.g. cached HUD assembly, just as
            # FILL does. Preserve bounds checks AND active-FB ownership checks.
            last = dst+(h-1)*dst_stride+4*w
            if not (self.in_scratch(dst) and last <= SCRATCH_BASE+SCRATCH_SIZE):
                print("BAD COPY dst=%#x src=%#x w=%d h=%d ss=%#x ds=%#x pc=%#x"
                      % (dst, src, w, h, src_stride, dst_stride, self.pc))
                for rec in self._blit_trace[-5:]:
                    print("   prev:", " ".join(str(x) for x in rec))
            assert self.in_scratch(dst) and last <= SCRATCH_BASE+SCRATCH_SIZE, \
                "BitBlt copy destination %#x outside modelled DDR" % dst
        self.drain()
        nbytes = w * 4
        key_bytes = None if colorkey is None else colorkey.to_bytes(4,'little')
        if colorkey is not None:
            assert (src | dst) & 3 == 0, "Color Key COPY must be pixel aligned"
        for r in range(h):
            data = self._region_read(src + r * src_stride, nbytes)
            # Exact fast path: absence even as an unaligned byte substring
            # proves no aligned pixel equals the key. Possible unaligned
            # matches conservatively take the original per-pixel path.
            if colorkey is None or key_bytes not in data:
                self._region_write(dst + r * dst_stride, data)
            else:
                assert (src | dst) & 3 == 0, "Color Key COPY must be pixel aligned"
                for x in range(w):
                    pixel = data[x * 4:x * 4 + 4]
                    if int.from_bytes(pixel, "little") != colorkey:
                        self._region_write(dst + r * dst_stride + x * 4, pixel)
        self.starts += 1
        self.blit_copy_calls += 1
        self.blit_copy_bytes += nbytes * h
        self.last_copy = (dst, src, w, h, src_stride, dst_stride)
        self.done = True
        self.busy_until = self.steps + self.latency

    def blit_alpha(self, dst, src, w, h, src_stride, dst_stride,
                   global_alpha=255, colorkey=None):
        """OP_ALPHA: blend an ARGB8888 sprite over the LIVE background.

        Mirrors rtl/bitblt/bitblt_alpha_blend.v exactly:

            ae  = (a * GLOBAL_ALPHA + 127) / 255
            out = (src * ae + dst * (255 - ae) + 127) / 255     for R, G, B

        The destination background is read back from DDR, so this is a real
        read-modify-write; the background alpha byte is passed through and a
        source pixel equal to the colour key is skipped entirely (colour keying
        has priority over blending).
        """
        self.drain()
        assert src_stride % 16 == 0 and dst_stride % 16 == 0, \
            "BitBlt alpha strides must be multiples of 16"
        assert (src | dst) & 3 == 0, "BitBlt alpha needs 32-bit pixel alignment"
        base = self.frame_of(dst)
        assert base is not None, "alpha destination %#x is not a framebuffer" % dst
        off = dst - base
        x = (off // 4) % SCREEN_PITCH
        y = (off // 4) // SCREEN_PITCH
        assert 0 <= x and x + w <= SCREEN_W and y + h <= SCREEN_H, \
            "BitBlt alpha out of bounds: (%d,%d,%d,%d)" % (x, y, w, h)
        self.check_owner(base, x=x, hw=True)
        self.drain()

        snapshot = []
        written = 0
        keyed = 0
        for r in range(h):
            sdata = self._region_read(src + r * src_stride, 4 * w)
            row = self.fb[base][(y + r) * SCREEN_PITCH + x:(y + r) * SCREEN_PITCH + x + w]
            dprev = b"".join(p.to_bytes(4, "little") for p in row)
            snapshot.append(dprev)

            out = bytearray(4 * w)
            for px in range(w):
                sp = sdata[px * 4:px * 4 + 4]
                dp = dprev[px * 4:px * 4 + 4]
                if colorkey is not None and int.from_bytes(sp, "little") == colorkey:
                    out[px * 4:px * 4 + 4] = dp        # untouched, not blended
                    keyed += 1
                    continue
                a = (sp[3] * global_alpha + 127) // 255
                for k in range(3):
                    out[px * 4 + k] = (sp[k] * a + dp[k] * (255 - a) + 127) // 255
                out[px * 4 + 3] = dp[3]                # background alpha passes through
                written += 4

            arr = array('I')
            arr.frombytes(bytes(out))
            self.fb[base][(y + r) * SCREEN_PITCH + x:(y + r) * SCREEN_PITCH + x + w] = arr

        self.starts += 1
        self.blit_alpha_calls += 1
        self.blit_alpha_bytes += written
        self.blit_alpha_keyed += keyed
        self.last_alpha = (dst, src, w, h, src_stride, dst_stride)
        self.last_alpha_cfg = (global_alpha, colorkey)
        self.last_alpha_before = snapshot
        self.last_alpha_rect = (x, y, w, h)
        self.done = True
        self.busy_until = self.steps + self.latency

    def blit_add(self, dst, src, w, h, src_stride, dst_stride, colorkey=None):
        """OP_ADD: additive blend an ARGB8888 sprite over the LIVE background."""
        self.drain()
        assert src_stride % 16 == 0 and dst_stride % 16 == 0, \
            "BitBlt add strides must be multiples of 16"
        assert (src | dst) & 3 == 0, "BitBlt add needs 32-bit pixel alignment"
        base = self.frame_of(dst)
        assert base is not None, "add destination %#x is not a framebuffer" % dst
        off = dst - base
        x = (off // 4) % SCREEN_PITCH
        y = (off // 4) // SCREEN_PITCH
        assert 0 <= x and x + w <= SCREEN_W and y + h <= SCREEN_H, \
            "BitBlt add out of bounds: (%d,%d,%d,%d)" % (x, y, w, h)
        self.check_owner(base, x=x, hw=True)
        self.drain()

        written = 0
        for r in range(h):
            sdata = self._region_read(src + r * src_stride, 4 * w)
            row = self.fb[base][(y + r) * SCREEN_PITCH + x:(y + r) * SCREEN_PITCH + x + w]
            dprev = b"".join(p.to_bytes(4, "little") for p in row)

            out = bytearray(4 * w)
            for px in range(w):
                sp = sdata[px * 4:px * 4 + 4]
                dp = dprev[px * 4:px * 4 + 4]
                if colorkey is not None and int.from_bytes(sp, "little") == colorkey:
                    out[px * 4:px * 4 + 4] = dp
                    continue
                for k in range(3):
                    val = sp[k] + dp[k]
                    out[px * 4 + k] = 255 if val > 255 else val
                out[px * 4 + 3] = dp[3]
                written += 4

            arr = array('I')
            arr.frombytes(bytes(out))
            self.fb[base][(y + r) * SCREEN_PITCH + x:(y + r) * SCREEN_PITCH + x + w] = arr

        self.starts += 1
        self.blit_add_calls += 1
        self.blit_add_bytes += written
        self.done = True
        self.busy_until = self.steps + self.latency

    def _apb_store(self, off, val):
        if off in (4, 8, 12, 16, 24, 28, 48, 72, 0x60, 0x64, 0x68, 0x6C):
            self.params[off] = val
        elif off == 20 and (val & 1):
            assert self.steps >= self.busy_until, "BitBlt START issued while busy"
            op = self.params.get(24, 0) & 3
            dst, w, h, color = (self.params.get(k, 0) for k in (4, 8, 12, 16))
            if op == 0:
                self.blit_fill(dst, w, h, color, self.params.get(72, 4096))
            elif op == 2:
                src = self.params.get(28, 0)
                key = self.params.get(0x60, 0x00FF00FF) \
                    if (self.params.get(0x64, 0) & 1) else None
                # the hardware rejects OP_ALPHA while ALPHA_CTRL[0] is clear
                assert self.params.get(0x68, 0) & 1, \
                    "OP_ALPHA issued with ALPHA_CTRL disabled (hardware raises CFGERR)"
                self.blit_alpha(dst, src, w, h,
                                self.params.get(48, 4096), self.params.get(72, 4096),
                                self.params.get(0x6C, 0xFF), key)
            elif op == 3:
                src = self.params.get(28, 0)
                key = self.params.get(0x60, 0x00FF00FF) \
                    if (self.params.get(0x64, 0) & 1) else None
                assert self.params.get(0x68, 0) & 1, \
                    "OP_ADD issued with ALPHA_CTRL disabled (hardware raises CFGERR)"
                self.blit_add(dst, src, w, h,
                              self.params.get(48, 4096), self.params.get(72, 4096), key)
            else:
                src = self.params.get(28, 0)
                key = self.params.get(0x60, 0x00FF00FF) \
                    if (self.params.get(0x64, 0) & 1) else None
                self.blit_copy(dst, src, w, h,
                               self.params.get(48, 4096), self.params.get(72, 4096), key)
        elif off == 0x40:
            assert val in FRAME_BASES
            self.right_request = val
            self.right_published.append(val)
        elif off == 0x5C:
            self.params[0x5C] = val
        elif off == 0x78:
            # Weather overlay control.  The real scanout synthesises the layer
            # in hardware; the VM has no scanout, so this is a no-op.
            self.params[0x78] = val
        elif off == 0x7C:
            # Color matrix control (scanout post-processing, no-op in VM)
            self.params[0x7C] = val
        elif off == 0x88:
            # Bloom filter control (scanout post-processing, no-op in VM)
            self.params[0x88] = val
        elif off == 0x80:
            # Asset ROM index (0x84 reads the byte back).  Modelled because the
            # firmware's boot path depends on it; see _load_asset_rom().
            self.asset_addr = val & 0x3FFF
        elif off == 0x20:
            assert not self.pending, "Published frame before DDR stores drained"
            assert val in FRAME_BASES, "published buffer %#x is out of range" % val
            assert self.steps >= self.busy_until, "published before BitBlt finished"
            self.request = val
            self.published.append(val)
        else:
            raise AssertionError("unknown APB write %#x" % off)

