    def step(self):
        assert RAM_BASE <= self.pc < self.image_end and self.pc & 3 == 0, \
            "bad PC %#x (image ends at %#x)" % (self.pc, self.image_end)
        ins = self.ram32[(self.pc - RAM_BASE) >> 2]
        op = ins & 0x7F
        rd = (ins >> 7) & 0x1F
        f3 = (ins >> 12) & 0x07
        rs1 = (ins >> 15) & 0x1F
        rs2 = (ins >> 20) & 0x1F
        f7 = ins >> 25

        a = self.r[rs1]
        b = self.r[rs2]
        npc = self.pc + 4
        result = None

        # Dispatched in order of measured frequency (see
        # temp/stage2_diag/probe_opcode.py): OP-IMM 40%, BRANCH 24%,
        # LOAD 16%, STORE 5.5%, LUI 5.3%, OP 4%, JALR 3.5%, AUIPC 1.8%,
        # JAL 0.4%.  An if-chain charges every instruction for the
        # branches in front of it, and the old order opened with LUI and
        # AUIPC - the two rarest things compiled C does.  Average compares
        # per instruction: 4.59 before, 2.50 after.
        if op == 0x13:                                  # OP-IMM
            imm = sign_extend(ins >> 20, 12)
            if f3 == 0:   result = a + imm
            elif f3 == 2: result = int(sign_extend(a, 32) < imm)
            elif f3 == 3: result = int(a < (imm & 0xFFFFFFFF))
            elif f3 == 4: result = a ^ imm
            elif f3 == 6: result = a | imm
            elif f3 == 7: result = a & imm
            elif f3 == 1 and f7 == 0x00: result = a << (rs2 & 0x1F)
            elif f3 == 5 and f7 == 0x00: result = a >> (rs2 & 0x1F)
            elif f3 == 5 and f7 == 0x20: result = sign_extend(a, 32) >> (rs2 & 0x1F)
            else: raise AssertionError("unknown OP-IMM %#x" % ins)
        elif op == 0x63:                                  # BRANCH
            imm = ((ins >> 31) << 12) | (((ins >> 7) & 1) << 11) | \
                  (((ins >> 25) & 0x3F) << 5) | (((ins >> 8) & 0x0F) << 1)
            # A chain, not a six-entry dict: this used to build and fill a
            # dict on every branch taken, and branches are a sixth of the
            # instructions a program executes.
            if f3 == 0:    take = a == b
            elif f3 == 1:  take = a != b
            elif f3 == 4:  take = sign_extend(a, 32) < sign_extend(b, 32)
            elif f3 == 5:  take = sign_extend(a, 32) >= sign_extend(b, 32)
            elif f3 == 6:  take = a < b
            elif f3 == 7:  take = a >= b
            else: raise AssertionError("unknown BRANCH %#x" % ins)
            if take:
                npc = self.pc + sign_extend(imm, 13)
        elif op == 0x03:                                  # LOAD
            addr = (a + sign_extend(ins >> 20, 12)) & 0xFFFFFFFF
            if f3 == 0:   result = self.load(addr, 1, signed=True)
            elif f3 == 1: result = self.load(addr, 2, signed=True)
            elif f3 == 2: result = self.load(addr, 4)
            elif f3 == 4: result = self.load(addr, 1)
            elif f3 == 5: result = self.load(addr, 2)
            else: raise AssertionError("unknown LOAD %#x" % ins)
        elif op == 0x23:                                  # STORE
            imm = ((ins >> 25) << 5) | ((ins >> 7) & 0x1F)
            addr = (a + sign_extend(imm, 12)) & 0xFFFFFFFF
            if f3 == 0:   self.store(addr, b, 1)
            elif f3 == 1: self.store(addr, b, 2)
            elif f3 == 2: self.store(addr, b, 4)
            else: raise AssertionError("unknown STORE %#x" % ins)
        elif op == 0x37:                                  # LUI
            result = ins & 0xFFFFF000
        elif op == 0x33:                                  # OP
            if f7 == 0x01:                                # RV32M
                sa = sign_extend(a, 32)
                sb = sign_extend(b, 32)
                if f3 == 0:    result = (a * b) & 0xFFFFFFFF                        # MUL
                elif f3 == 1:  result = ((sa * sb) >> 32) & 0xFFFFFFFF             # MULH
                elif f3 == 2:  result = ((sa * b) >> 32) & 0xFFFFFFFF              # MULHSU
                elif f3 == 3:  result = ((a * b) >> 32) & 0xFFFFFFFF               # MULHU
                elif f3 == 4:                                                       # DIV
                    if sb == 0: result = 0xFFFFFFFF
                    elif sa == -0x80000000 and sb == -1: result = 0x80000000
                    else:
                        q = abs(sa) // abs(sb)
                        result = (-q if (sa < 0) ^ (sb < 0) else q) & 0xFFFFFFFF
                elif f3 == 5:  result = 0xFFFFFFFF if b == 0 else (a // b) & 0xFFFFFFFF # DIVU
                elif f3 == 6:                                                       # REM
                    if sb == 0: result = a
                    elif sa == -0x80000000 and sb == -1: result = 0
                    else:
                        r = abs(sa) % abs(sb)
                        result = (-r if sa < 0 else r) & 0xFFFFFFFF
                elif f3 == 7:  result = a if b == 0 else (a % b) & 0xFFFFFFFF      # REMU
                else: raise AssertionError("unknown RV32M %#x" % ins)
            elif f3 == 0 and f7 == 0x00:   result = a + b
            elif f3 == 0 and f7 == 0x20: result = a - b
            elif f3 == 1 and f7 == 0x00: result = a << (b & 0x1F)
            elif f3 == 2 and f7 == 0x00: result = int(sign_extend(a, 32) < sign_extend(b, 32))
            elif f3 == 3 and f7 == 0x00: result = int(a < b)
            elif f3 == 4 and f7 == 0x00: result = a ^ b
            elif f3 == 5 and f7 == 0x00: result = a >> (b & 0x1F)
            elif f3 == 5 and f7 == 0x20: result = sign_extend(a, 32) >> (b & 0x1F)
            elif f3 == 6 and f7 == 0x00: result = a | b
            elif f3 == 7 and f7 == 0x00: result = a & b
            else: raise AssertionError("unknown OP %#x" % ins)
        elif op == 0x67 and f3 == 0:                      # JALR
            result = npc
            npc = (a + sign_extend(ins >> 20, 12)) & ~1
        elif op == 0x17:                                  # AUIPC
            result = (self.pc + (ins & 0xFFFFF000)) & 0xFFFFFFFF
        elif op == 0x6F:                                  # JAL
            imm = ((ins >> 31) << 20) | (((ins >> 12) & 0xFF) << 12) | \
                  (((ins >> 20) & 1) << 11) | (((ins >> 21) & 0x3FF) << 1)
            result = npc
            npc = self.pc + sign_extend(imm, 21)
        elif ins == 0x0000500F:                           # Sapphire dcache flush
            # write back and invalidate, i.e. the CPU-side writes become
            # visible in DDR (gpu2d_flush_dcache in sw/driver/gpu2d.c)
            self.drain()
        elif ins == 0x0000000F:                           # FENCE
            pass
        elif op == 0x0F and f3 == 0:                      # FENCE / FENCE.I
            pass


        else:
            raise AssertionError("illegal instruction %#010x at PC=%#x" % (ins, self.pc))

        if result is not None and rd != 0:
            self.r[rd] = result & 0xFFFFFFFF

        sp = self.r[2]
        if RAM_BASE <= sp < RAM_BASE + RAM_SIZE and sp < self.min_sp:
            # Only a new low can change either value, so the floor check runs
            # here rather than on every in-range sp: same guarantee, two
            # compares instead of a min() call per instruction.
            self.min_sp = sp
            assert sp >= self.stack_floor, \
                "stack overflow: sp=%#x below floor %#x" % (sp, self.stack_floor)

        self.pc = npc & 0xFFFFFFFF
        self.steps += 1

        # 60 Hz display refresh tick.  A countdown, not `steps % TICK_STEPS`:
        # the modulo ran on every instruction to answer a question that is
        # true once in 25000, and a decrement plus a compare is far cheaper.
        self.tick_left -= 1
        if self.tick_left <= 0:
            self.tick_left = TICK_STEPS
            if self.active != self.request:
                self.cpu_frames = (self.cpu_frames + 1) & 0xFFFFFFFF
            if self.right_active != self.right_request:
                self.fpga_frames = (self.fpga_frames + 1) & 0xFFFFFFFF
            self.active = self.request
            self.right_active = self.right_request
            self.vsync = True

